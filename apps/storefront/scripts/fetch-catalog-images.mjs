#!/usr/bin/env node
/**
 * Downloads catalog photography from Pixabay for every department, category and
 * product in src/catalog/data.ts. Files go to public/catalog/ and are recorded in
 * src/catalog/image-manifest.ts (a TS module, so builds never trace it as a file).
 *
 *   1. Put your key in apps/storefront/.env.local →  PIXABAY_API_KEY=xxxxxxxx
 *   2. npm run images:fetch
 *
 *   npm run images:fetch -- --only signage-displays          # one department
 *   npm run images:fetch -- --fresh                          # start over
 *   npm run images:fetch -- --redo p:bags/pouches/zipper-pouch --query "zip lock bag"
 *
 * Matching rules live in scripts/image-curation.mjs. Pixabay rules respected:
 * images are downloaded (no hotlinking), API responses are cached for 24h, and the
 * 100 requests / minute limit is honoured. Resumable: finished keys are skipped.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { CATEGORIES, DEPARTMENTS, GLOBAL_EXCLUDE } from './image-curation.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = path.join(root, 'src/catalog/image-manifest.ts')
const legacyManifestPath = path.join(root, 'src/catalog/image-manifest.json')

const HEADER = '// Generated by scripts/fetch-catalog-images.mjs — do not edit by hand.\n'

function readManifest() {
   // Older runs stored the manifest as JSON; migrate it on first read.
   if (fs.existsSync(legacyManifestPath)) return JSON.parse(fs.readFileSync(legacyManifestPath, 'utf8'))
   if (!fs.existsSync(manifestPath)) return {}
   const text = fs.readFileSync(manifestPath, 'utf8')
   const start = text.indexOf('{')
   const end = text.lastIndexOf('}')
   return start >= 0 ? JSON.parse(text.slice(start, end + 1)) : {}
}

function writeManifest(manifest) {
   const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)))
   fs.writeFileSync(manifestPath, `${HEADER}const manifest = ${JSON.stringify(sorted, null, 1)}\n\nexport default manifest\n`)
   if (fs.existsSync(legacyManifestPath)) fs.rmSync(legacyManifestPath)
}
const publicDir = path.join(root, 'public')
const catalogDir = path.join(publicDir, 'catalog')
const cacheDir = path.join(root, 'node_modules/.cache/pixabay')

function readKey() {
   if (process.env.PIXABAY_API_KEY) return process.env.PIXABAY_API_KEY.trim()
   for (const file of ['.env.local', '.env']) {
      const p = path.join(root, file)
      if (!fs.existsSync(p)) continue
      const match = fs.readFileSync(p, 'utf8').match(/^PIXABAY_API_KEY\s*=\s*["']?([^"'\r\n]+)["']?/m)
      if (match) return match[1].trim()
   }
   return null
}

const arg = (name) => {
   const i = process.argv.indexOf(name)
   return i >= 0 ? process.argv[i + 1] : undefined
}
const flag = (name) => process.argv.includes(name)

const slugify = (v) =>
   v.trim().toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')

const STOP = new Set(['and', 'the', 'for', 'with', 'custom', 'branded', 'printed'])
const words = (text) =>
   text
      .toLowerCase()
      .split(/[^a-z0-9]+/)
      .filter((w) => w.length > 2 && !STOP.has(w))
      .map((w) => w.replace(/s$/, ''))

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

/* ───────────── Pixabay API (cached 24h, rate limited) ───────────── */

async function search(key, query) {
   fs.mkdirSync(cacheDir, { recursive: true })
   const cacheFile = path.join(cacheDir, `${slugify(query)}-60.json`)
   if (fs.existsSync(cacheFile) && Date.now() - fs.statSync(cacheFile).mtimeMs < 24 * 3600 * 1000) {
      return JSON.parse(fs.readFileSync(cacheFile, 'utf8'))
   }
   const url =
      `https://pixabay.com/api/?key=${encodeURIComponent(key)}` +
      `&q=${encodeURIComponent(query.slice(0, 100))}` +
      `&image_type=photo&orientation=horizontal&safesearch=true&min_width=900&per_page=60`

   for (;;) {
      const res = await fetch(url)
      if (res.status === 429) {
         const wait = (Number(res.headers.get('x-ratelimit-reset')) || 60) * 1000 + 1000
         console.log(`  rate limited — waiting ${Math.round(wait / 1000)}s`)
         await sleep(wait)
         continue
      }
      if (res.status === 400) {
         const text = await res.text()
         if (/key/i.test(text)) throw new Error(`Pixabay rejected the API key: ${text}`)
         return { hits: [] }
      }
      if (!res.ok) throw new Error(`Pixabay HTTP ${res.status}`)
      const data = await res.json()
      fs.writeFileSync(cacheFile, JSON.stringify(data))
      const remaining = Number(res.headers.get('x-ratelimit-remaining'))
      await sleep(remaining <= 2 ? (Number(res.headers.get('x-ratelimit-reset')) || 60) * 1000 + 1000 : 650)
      return data
   }
}

async function download(url, dest) {
   const res = await fetch(url)
   if (!res.ok) throw new Error(`HTTP ${res.status}`)
   const buf = Buffer.from(await res.arrayBuffer())
   const expected = Number(res.headers.get('content-length'))
   if (expected && buf.length !== expected) throw new Error('incomplete download')
   if (buf.length < 4000) throw new Error('file too small')
   fs.mkdirSync(path.dirname(dest), { recursive: true })
   const tmp = `${dest}.part`
   fs.writeFileSync(tmp, buf)
   fs.renameSync(tmp, dest)
}

/* ───────────── Matching ───────────── */

function tagList(hit) {
   return (hit.tags ?? '').toLowerCase().split(',').map((t) => t.trim()).filter(Boolean)
}

function passes(hit, rule) {
   const tags = tagList(hit)
   const text = ` ${tags.join(' ')} `
   const tokens = new Set(text.split(/[^a-z0-9-]+/).filter(Boolean))
   const banned = [...GLOBAL_EXCLUDE, ...(rule.exclude ?? [])]
   if (banned.some((b) => tokens.has(b))) return false
   if (!rule.must?.length) return true
   return rule.must.some((m) => (m.includes(' ') ? text.includes(` ${m} `) : tokens.has(m) || tokens.has(`${m}s`)))
}

function relevance(hit, query) {
   const wanted = [...new Set(words(query))]
   if (!wanted.length) return 0
   const tags = new Set(words(tagList(hit).join(' ')))
   const head = wanted[wanted.length - 1]
   const matched = wanted.filter((w) => tags.has(w))
   return (matched.length + (matched.includes(head) ? 1 : 0)) / (wanted.length + 1)
}

/* ───────────── Main ───────────── */

async function main() {
   const key = readKey()
   if (!key) {
      console.error('\nMissing PIXABAY_API_KEY.\nAdd it to apps/storefront/.env.local like this:\n\n   PIXABAY_API_KEY=your-key-here\n')
      process.exit(1)
   }

   const { DEPARTMENT_SEEDS } = await import(
      new URL('file:///' + path.join(root, 'src/catalog/data.ts').replace(/\\/g, '/'))
   )

   /** Marketing → Flyers etc. reuse another category's photos */
   const CATEGORY_ALIAS = {}
   for (const d of DEPARTMENT_SEEDS) {
      for (const c of d.categories) if (c.aliasOf) CATEGORY_ALIAS[`${d.slug}/${c.slug}`] = c.aliasOf
   }

   if (flag('--fresh')) {
      fs.rmSync(catalogDir, { recursive: true, force: true })
      writeManifest({})
   }

   const manifest = readManifest()
   for (const [k, v] of Object.entries(manifest)) {
      if (!v.file || !fs.existsSync(path.join(publicDir, v.file))) delete manifest[k]
   }

   /* Build jobs */
   const jobs = []
   for (const d of DEPARTMENT_SEEDS) {
      const deptRule = DEPARTMENTS[d.slug] ?? { queries: [d.imageQuery], must: [] }
      jobs.push({ key: `d:${d.slug}`, label: d.name, large: true, rule: deptRule, own: null })
      for (const c of d.categories) {
         const ckey = `${d.slug}/${c.slug}`
         const rule = CATEGORIES[c.aliasOf ?? ckey] ?? { queries: [c.imageQuery ?? c.name], must: [] }
         jobs.push({ key: `c:${ckey}`, label: c.name, large: true, rule, own: null })
         for (const [name, , , q] of c.products) {
            jobs.push({ key: `p:${ckey}/${slugify(name)}`, label: name, large: false, rule, own: q ?? name })
         }
      }
   }

   /* ── Review workflow ──────────────────────────────────────────────
    * --candidates   save up to 64 rule-passing photos per category for review
    * --apply-picks  use the hand-picked photo IDs in scripts/image-picks.mjs
    */
   const candidatesDir = path.join(cacheDir, 'candidates')
   const categoryJobs = new Map()
   for (const job of jobs) {
      if (!job.key.startsWith('p:')) continue
      const ckey = job.key.slice(2).split('/').slice(0, 2).join('/')
      if (!categoryJobs.has(ckey)) categoryJobs.set(ckey, [])
      categoryJobs.get(ckey).push(job)
   }

   if (flag('--candidates')) {
      fs.mkdirSync(candidatesDir, { recursive: true })
      for (const [ckey, rule] of Object.entries(CATEGORIES)) {
         const seen = new Set()
         const list = []
         const add = (hits) => {
            for (const hit of hits ?? []) {
               if (list.length >= 64) return
               if (seen.has(hit.id) || !passes(hit, rule)) continue
               seen.add(hit.id)
               list.push({
                  id: hit.id,
                  previewURL: hit.previewURL,
                  webformatURL: hit.webformatURL,
                  largeImageURL: hit.largeImageURL,
                  imageWidth: hit.imageWidth,
                  imageHeight: hit.imageHeight,
                  tags: hit.tags,
                  user: hit.user,
                  user_id: hit.user_id,
                  pageURL: hit.pageURL,
               })
            }
         }
         // Interleave: a few from every category query, then product-specific searches
         const results = []
         for (const q of rule.queries) results.push((await search(key, q)).hits ?? [])
         for (let round = 0; round < 12 && list.length < 48; round++) {
            for (const hits of results) add(hits.slice(round * 4, round * 4 + 4))
         }
         for (const job of categoryJobs.get(ckey) ?? []) {
            if (list.length >= 64) break
            add(((await search(key, job.own)).hits ?? []).slice(0, 4))
         }
         fs.writeFileSync(path.join(candidatesDir, `${slugify(ckey)}.json`), JSON.stringify(list))
         console.log(`${ckey}: ${list.length} candidates`)
      }
      return
   }

   if (flag('--apply-picks')) {
      const { PICKS, DEPARTMENT_PICKS } = await import('./image-picks.mjs')
      const byId = new Map()
      for (const f of fs.readdirSync(candidatesDir)) {
         for (const c of JSON.parse(fs.readFileSync(path.join(candidatesDir, f), 'utf8'))) byId.set(c.id, c)
      }
      const assign = []
      for (const job of jobs) {
         const kind = job.key[0]
         const body = job.key.slice(2)
         if (kind === 'd' && DEPARTMENT_PICKS[body]) assign.push([job, DEPARTMENT_PICKS[body]])
         if (kind === 'c') {
            const picks = PICKS[CATEGORY_ALIAS[body] ?? body]
            if (picks?.length) assign.push([job, picks[0]])
         }
      }
      for (const [ckey, catJobs] of categoryJobs) {
         const picks = PICKS[CATEGORY_ALIAS[ckey] ?? ckey]
         if (!picks?.length) continue
         const usage = new Map(picks.map((id) => [id, 0]))
         // Products get the most relevant approved photo, spreading use as evenly as possible
         for (const job of catJobs) {
            const best = picks
               .map((id, index) => ({ id, score: relevance(byId.get(id) ?? {}, job.own) * 10 - usage.get(id) * 4 - index * 0.01 }))
               .sort((a, b) => b.score - a.score)[0]
            usage.set(best.id, usage.get(best.id) + 1)
            assign.push([job, best.id])
         }
      }

      let saved = 0
      for (const [job, id] of assign) {
         const pick = byId.get(id)
         if (!pick) {
            console.warn(`! ${job.key}: photo ${id} not in candidates`)
            continue
         }
         const wantSize = job.large ? 960 : 640
         const ext = path.extname(new URL(pick.webformatURL).pathname) || '.jpg'
         const file = `/catalog/${job.key.replace(':', '/')}${ext}`
         const existing = manifest[job.key]
         if (existing?.id === id && existing.file === file && fs.existsSync(path.join(publicDir, file))) continue
         let size = 0
         for (const [src, w] of [
            [pick.webformatURL.replace(/_640(\.\w+)$/, `_${wantSize}$1`), wantSize],
            [pick.largeImageURL, 1280],
            [pick.webformatURL, 640],
         ]) {
            try {
               await download(src, path.join(publicDir, file))
               size = w
               break
            } catch {
               // try the next rendition
            }
         }
         if (!size) {
            console.warn(`! ${job.key}: download failed`)
            continue
         }
         if (existing?.file && existing.file !== file) fs.rmSync(path.join(publicDir, existing.file), { force: true })
         manifest[job.key] = {
            id,
            file,
            width: size,
            height: Math.round((size * pick.imageHeight) / pick.imageWidth),
            alt: `${job.label} — ${tagList(pick).slice(0, 6).join(', ')}`,
            photographer: pick.user,
            photographerUrl: `https://pixabay.com/users/${pick.user}-${pick.user_id}/`,
            pageUrl: pick.pageURL,
            source: 'pixabay',
         }
         saved++
         if (saved % 10 === 0) writeManifest(manifest)
      }
      writeManifest(manifest)
      console.log(`Applied picks: ${saved} images updated (${assign.length} assigned).`)
      return
   }

   const only = arg('--only')
   const redo = arg('--redo')
   let todo = jobs.filter((j) => !manifest[j.key])
   if (only) todo = todo.filter((j) => j.key.slice(2).startsWith(only))
   if (redo) {
      const job = jobs.find((j) => j.key === redo)
      if (!job) throw new Error(`Unknown key ${redo}`)
      job.exclude = manifest[redo]?.id
      delete manifest[redo]
      if (arg('--query')) job.own = arg('--query')
      todo = [job]
   }

   const used = new Set(Object.values(manifest).map((e) => e.id))
   const save = () => writeManifest(manifest)
   console.log(`${jobs.length} images in catalog · ${jobs.length - todo.length} done · ${todo.length} to fetch\n`)

   /** Category pools: candidates from the curated queries, in ranked order */
   const pools = new Map()
   async function pool(rule) {
      const id = JSON.stringify(rule.queries)
      if (pools.has(id)) return pools.get(id)
      const seen = new Set()
      const list = []
      for (const q of rule.queries) {
         const data = await search(key, q)
         for (const hit of data.hits ?? []) {
            if (seen.has(hit.id) || !passes(hit, rule)) continue
            seen.add(hit.id)
            list.push(hit)
         }
      }
      pools.set(id, list)
      return list
   }

   let failed = 0
   let shared = 0
   for (const [i, job] of todo.entries()) {
      let pick = null
      let how = ''

      // 1. The product's own search — only if the photo passes the category rules
      if (job.own) {
         const data = await search(key, job.own)
         const best = (data.hits ?? [])
            .filter((h) => !used.has(h.id) && h.id !== job.exclude && passes(h, job.rule))
            .map((hit, index) => ({ hit, score: relevance(hit, job.own) * 100 - index * 0.5 }))
            .sort((a, b) => b.score - a.score)[0]
         if (best && relevance(best.hit, job.own) >= 0.5) {
            pick = best.hit
            how = `"${job.own}"`
         }
      }

      // 2. The category's curated pool (next unused photo)
      if (!pick) {
         const list = await pool(job.rule)
         pick = list.find((h) => !used.has(h.id) && h.id !== job.exclude) ?? null
         how = 'category pool'
         if (!pick && list.length) {
            // Pool exhausted: reuse the best photo rather than show a placeholder
            pick = list.find((h) => h.id !== job.exclude) ?? list[0]
            how = 'category pool (shared)'
            shared++
         }
      }

      if (!pick) {
         failed++
         console.warn(`! [${i + 1}/${todo.length}] ${job.key}: nothing suitable`)
         continue
      }

      const wantSize = job.large ? 960 : 640
      const ext = path.extname(new URL(pick.webformatURL).pathname) || '.jpg'
      const file = `/catalog/${job.key.replace(':', '/')}${ext}`
      let size = 0
      for (const [src, w] of [
         [pick.webformatURL.replace(/_640(\.\w+)$/, `_${wantSize}$1`), wantSize],
         [pick.largeImageURL, 1280],
         [pick.webformatURL, 640],
      ]) {
         try {
            await download(src, path.join(publicDir, file))
            size = w
            break
         } catch {
            // try the next rendition
         }
      }
      if (!size) {
         failed++
         console.warn(`! ${job.key}: download failed`)
         continue
      }

      used.add(pick.id)
      manifest[job.key] = {
         id: pick.id,
         file,
         width: size,
         height: Math.round((size * pick.imageHeight) / pick.imageWidth),
         alt: `${job.label} — ${tagList(pick).slice(0, 6).join(', ')}`,
         photographer: pick.user,
         photographerUrl: `https://pixabay.com/users/${pick.user}-${pick.user_id}/`,
         pageUrl: pick.pageURL,
         source: 'pixabay',
      }
      if ((i + 1) % 10 === 0) save()
      console.log(`✓ [${i + 1}/${todo.length}] ${job.key}  ←  ${how}`)
   }

   save()
   console.log(
      `\nDone. ${todo.length - failed} saved${shared ? ` (${shared} share a photo)` : ''}${failed ? `, ${failed} failed — run again to retry` : ''}.`
   )
}

main().catch((error) => {
   console.error('\n' + error.message)
   process.exit(1)
})
